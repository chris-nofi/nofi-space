"""python -m earth_oracle.cli <cmd> [--farm id|all]

NASA pulls: power | ecostress | hls | dswx      engine: train | analyze | plots
real data:  import-real   (Kepler's package in data/ → oracle/data/real/*.json engine inputs)
site:       export-site   (site/si-data.js: SI results + monthly record summaries)
plan v2:    export-evidence --periods 202608,202609,202610 --out ../avalanche/x402/data
            (one JSON per farm-month with dataHash; the x402 oracle sells exactly these bytes)
"""
from __future__ import annotations

import argparse
import json

from .config import load_farms
from .evidence import plot_hash


def _periods(arg: str | None) -> list[str]:
    from .ceres.tools import default_period

    if not arg:
        last = default_period()
        y, m = int(last[:4]), int(last[4:])
        out = []
        for _ in range(4):
            out.insert(0, f"{y:04d}{m:02d}")
            y, m = (y, m - 1) if m > 1 else (y - 1, 12)
        return out
    return [p.strip() for p in arg.split(",") if p.strip()]


def main() -> None:
    ap = argparse.ArgumentParser(prog="earth_oracle")
    ap.add_argument("cmd", choices=["power", "ecostress", "hls", "dswx", "plots", "train", "analyze", "export-site", "export-evidence", "import-real"])
    ap.add_argument("--farm", default="all")
    ap.add_argument("--periods", default=None, help="comma-separated YYYYMM (default: last closed month)")
    ap.add_argument("--out", default=None, help="output folder for export-evidence")
    args = ap.parse_args()
    farms = load_farms()
    targets = list(farms.values()) if args.farm == "all" else [farms[args.farm]]

    if args.cmd == "train":
        from .si.model import train

        card = train(save=True)
        print(json.dumps({k: card[k] for k in ("trainingData", "rows", "comparison", "selected")}, indent=2))
        return
    if args.cmd == "import-real":
        from .real_data import import_all

        for p in import_all():
            print("wrote", p)
        return
    periods = _periods(args.periods)
    if args.cmd == "export-evidence":
        from pathlib import Path

        from .proof import export

        dest = Path(args.out or Path(__file__).resolve().parents[2] / "avalanche" / "x402" / "data")
        ids = [f.id for f in targets]
        for path in export(dest, periods, ids):
            pkg = json.loads(path.read_text(encoding="utf-8"))
            print(f"{path.name}  {pkg['dataHash']}  placeholder={pkg['placeholder']}")
        return
    if args.cmd == "export-site":
        from pathlib import Path

        from .proof import package, summary
        from .si.engine import analyze

        out = {f.id: analyze(f.id, draws=300) for f in load_farms().values()}
        for a in out.values():
            a.pop("waterUse", None)
        recs = {f.id: [summary(package(f.id, p)) for p in periods] for f in load_farms().values()}
        from .real_data import read_input

        def climate_view(fid: str) -> dict | None:
            pw, eco, nd, ctx = (read_input(f"{fid}_{k}.json") for k in ("power", "ecostress", "ndvi", "context"))
            if not pw:
                return None
            days = [31, 28.25, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
            return {
                "rainMonthlyMm": [round(v * d, 1) for v, d in zip(pw["rainMmDayMonthly"], days)],
                "rainRangeMmYr": pw.get("rainRangeMmYr"), "et0MmDay": pw.get("et0MmDayMonthly"),
                "tmaxMonthly": pw["tmaxMonthly"], "tminMonthly": pw["tminMonthly"], "provenance": pw.get("provenance"),
                "ecostress": {k: (eco or {}).get(k) for k in ("etMonthly", "overpassesMonthly", "totalValid", "first", "last", "representative")},
                "ndvi": {k: (nd or {}).get(k) for k in ("monthly", "source", "representative", "latest", "first", "last")},
                "trendT2m": ((ctx or {}).get("trends") or {}).get("t2m"),
                "point": (ctx or {}).get("point"),
            }

        clim = {f.id: climate_view(f.id) for f in load_farms().values()}
        js = ("/* Generated by oracle/earth_oracle (python -m earth_oracle.cli export-site). Default priorities, no scenario, 300 draws.\n"
              "   Inputs: REAL NASA POWER / CHIRPS / ERA5 / ECOSTRESS / MODIS (data/, Kepler 2026-11-14). The SI water-use model is still trained on synthetic data; yields/prices are examples.\n"
              "   AGUA_SI_RECORDS: monthly earth-record summaries (dataHash); placeholder=true means not anchored on chain. */\n"
              "window.AGUA_SI_FIXTURES = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
              "window.AGUA_SI_RECORDS = " + json.dumps(recs, ensure_ascii=False, separators=(",", ":")) + ";\n"
              "window.AGUA_SI_CLIMATE = " + json.dumps(clim, ensure_ascii=False, separators=(",", ":")) + ";\n")
        dest = Path(__file__).resolve().parents[2] / "site" / "si-data.js"
        dest.write_text(js, encoding="utf-8")
        print(f"wrote {dest} ({len(js)} bytes)")
        return
    if args.cmd == "analyze":
        from .si.engine import analyze

        for f in targets:
            a = analyze(f.id)
            print(f"== {f.id}: {a['voice']['es']['text']}")
        return
    if args.cmd == "plots":
        for f in targets:
            print(f.id, plot_hash(f))
        return
    if args.cmd == "dswx":
        from .dswx import extract

        print(json.dumps(extract(), indent=2)[:2000])
        return
    for f in targets:
        if args.cmd == "power":
            from .power import pull_and_cache

            s = pull_and_cache(f)
            print(f"{f.id}: rain {s['rainYearMm']} mm/yr · coldest Tmin {s['tminColdest']} °C · ET0 {s['et0Monthly']}")
        elif args.cmd == "ecostress":
            from .ecostress import extract

            r = extract(f)
            print(f"{f.id}: {len(r['overpasses'])} overpasses · {r['monthsWithData']} months · {r['etMonthly']}")
        elif args.cmd == "hls":
            from .hls import extract

            r = extract(f)
            print(f"{f.id}: {len(r['series'])} NDVI points · cropAlive={r['cropAlive']}")


if __name__ == "__main__":
    main()
